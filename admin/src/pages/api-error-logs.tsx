import React, { useEffect, useState } from "react";
import RootLayout from "@/component/layout/Layout";
import { useAppDispatch } from "@/store/store";
import { useSelector } from "react-redux";
import {
  fetchApiErrorLogs,
  clearApiErrorLogs,
  triggerTestError,
} from "@/store/systemMonitorSlice";
import { toast } from "react-toastify";
import Swal from "sweetalert2";

const ApiErrorLogsPage = () => {
  const dispatch = useAppDispatch();
  const {
    logs,
    logSummary,
    pagination,
    loadingLogs,
    clearingLogs,
  } = useSelector((state: any) => state.systemMonitor);

  const [searchQuery, setSearchQuery] = useState("");
  const [methodFilter, setMethodFilter] = useState("ALL");
  const [statusFilter, setStatusFilter] = useState("ALL");
  const [selectedError, setSelectedError] = useState<any | null>(null);
  const [isRefreshing, setIsRefreshing] = useState(false);

  useEffect(() => {
    loadLogs(1, searchQuery, methodFilter, statusFilter);
    const interval = setInterval(() => {
      loadLogs(pagination.page || 1, searchQuery, methodFilter, statusFilter);
    }, 15000);
    return () => clearInterval(interval);
  }, [dispatch]);

  const loadLogs = (page = 1, search = searchQuery, method = methodFilter, status = statusFilter) => {
    dispatch(
      fetchApiErrorLogs({
        page,
        search,
        method,
        status,
      })
    );
  };

  const handleRefresh = async () => {
    setIsRefreshing(true);
    await dispatch(
      fetchApiErrorLogs({
        page: pagination.page || 1,
        search: searchQuery,
        method: methodFilter,
        status: statusFilter,
      })
    );
    setTimeout(() => setIsRefreshing(false), 400);
  };

  const handleSearchChange = (e: React.ChangeEvent<HTMLInputElement>) => {
    const val = e.target.value;
    setSearchQuery(val);
    loadLogs(1, val, methodFilter, statusFilter);
  };

  const handleMethodChange = (e: React.ChangeEvent<HTMLSelectElement>) => {
    const val = e.target.value;
    setMethodFilter(val);
    loadLogs(1, searchQuery, val, statusFilter);
  };

  const handleStatusChange = (e: React.ChangeEvent<HTMLSelectElement>) => {
    const val = e.target.value;
    setStatusFilter(val);
    loadLogs(1, searchQuery, methodFilter, val);
  };

  const handleClearLogs = async () => {
    const result = await Swal.fire({
      title: "Clear all API error logs?",
      text: "This will remove all error traces and reset error counters. This action cannot be undone.",
      icon: "warning",
      showCancelButton: true,
      confirmButtonColor: "#EF4444",
      cancelButtonColor: "#6B7280",
      confirmButtonText: "Yes, Clear Logs",
    });

    if (result.isConfirmed) {
      const res: any = await dispatch(clearApiErrorLogs());
      if (res?.payload?.status) {
        toast.success("API error logs cleared successfully!");
      }
    }
  };

  const handleSimulateTestError = async () => {
    toast.info("Triggering simulated diagnostic 500 error...");
    await dispatch(
      triggerTestError({
        status: 500,
        message: `Diagnostic Alert generated by Administrator at ${new Date().toLocaleTimeString()}`,
      })
    );
    handleRefresh();
  };

  const getMethodBadgeClass = (method: string) => {
    switch (method?.toUpperCase()) {
      case "GET":
        return "bg-primary text-white";
      case "POST":
        return "bg-success text-white";
      case "PUT":
        return "bg-warning text-dark";
      case "PATCH":
        return "bg-info text-white";
      case "DELETE":
        return "bg-danger text-white";
      default:
        return "bg-secondary text-white";
    }
  };

  const getStatusBadgeStyle = (status: number) => {
    if (status >= 500) {
      return { backgroundColor: "#FEE2E2", color: "#DC2626", border: "1px solid #FCA5A5" };
    }
    if (status >= 400) {
      return { backgroundColor: "#FEF3C7", color: "#D97706", border: "1px solid #FCD34D" };
    }
    return { backgroundColor: "#DCFCE7", color: "#16A34A", border: "1px solid #86EFAC" };
  };

  return (
    <div style={{ background: "#F8FAFC", minHeight: "100vh", padding: "24px 20px 48px" }}>
      {/* ─── Top Header (Matching Screenshot 2) ───────────────────── */}
      <div
        className="d-flex flex-column flex-md-row justify-content-between align-items-md-center gap-3 mb-4 bg-white rounded-4 shadow-sm"
        style={{ padding: "20px 24px", border: "1px solid #E2E8F0" }}
      >
        <div className="d-flex align-items-center gap-3">
          <div
            className="d-flex align-items-center justify-content-center rounded-3 shadow-sm"
            style={{ width: 46, height: 46, backgroundColor: "#FEE2E2", color: "#EF4444" }}
          >
            <i className="ri-bug-line fs-24"></i>
          </div>
          <div>
            <h4 className="fw-bold text-dark mb-0" style={{ fontSize: "20px" }}>
              API Error Logs
            </h4>
            <p className="text-secondary small mb-0" style={{ fontSize: "12px" }}>
              System-wide real-time tracking of failed API calls, exceptions, and error traces
            </p>
          </div>
        </div>

        {/* Action Buttons (Refresh & Clear Logs) */}
        <div className="d-flex align-items-center gap-2 flex-wrap">
          <button
            type="button"
            className="btn btn-sm btn-outline-secondary rounded-pill d-inline-flex align-items-center gap-1"
            style={{ fontSize: "12px", padding: "6px 14px" }}
            onClick={handleSimulateTestError}
            title="Create a test 500 error to verify tracking"
          >
            <i className="ri-flask-line"></i> Simulate Test Error
          </button>
          <button
            type="button"
            className="btn btn-sm rounded-pill d-inline-flex align-items-center gap-1 text-white shadow-sm"
            style={{ fontSize: "12px", padding: "6px 18px", backgroundColor: "#0284C7", border: "none" }}
            onClick={handleRefresh}
          >
            <i className={`ri-refresh-line ${isRefreshing ? "spin-anim" : ""}`}></i> Refresh
          </button>
          <button
            type="button"
            className="btn btn-sm rounded-pill d-inline-flex align-items-center gap-1 text-white shadow-sm"
            style={{ fontSize: "12px", padding: "6px 18px", backgroundColor: "#F87171", border: "none" }}
            onClick={handleClearLogs}
            disabled={clearingLogs}
          >
            <i className="ri-delete-bin-line"></i> Clear Logs
          </button>
        </div>
      </div>

      {/* ─── Summary Stat Cards (Exact match to Screenshot 2) ─────── */}
      <div className="row g-3 mb-4">
        {/* TOTAL ERROR LOGS */}
        <div className="col-12 col-sm-6 col-xl-3">
          <div
            className="card border-0 rounded-4 p-3 bg-white shadow-sm h-100"
            style={{ border: "1px solid #E2E8F0" }}
          >
            <div className="d-flex justify-content-between align-items-center mb-1">
              <span className="text-secondary fw-bold" style={{ fontSize: "11px", letterSpacing: "0.5px" }}>
                TOTAL ERROR LOGS
              </span>
              <div
                className="d-flex align-items-center justify-content-center rounded-3"
                style={{ width: 34, height: 34, backgroundColor: "#F1F5F9", color: "#64748B" }}
              >
                <i className="ri-stack-line fs-17"></i>
              </div>
            </div>
            <h3 className="fw-bold text-dark mb-0 mt-2" style={{ fontSize: "28px" }}>
              {logSummary.totalErrorLogs}
            </h3>
          </div>
        </div>

        {/* 500 SERVER ERRORS */}
        <div className="col-12 col-sm-6 col-xl-3">
          <div
            className="card border-0 rounded-4 p-3 bg-white shadow-sm h-100"
            style={{ border: "1px solid #E2E8F0" }}
          >
            <div className="d-flex justify-content-between align-items-center mb-1">
              <span className="text-danger fw-bold" style={{ fontSize: "11px", letterSpacing: "0.5px" }}>
                500 SERVER ERRORS
              </span>
              <div
                className="d-flex align-items-center justify-content-center rounded-3"
                style={{ width: 34, height: 34, backgroundColor: "#FEE2E2", color: "#EF4444" }}
              >
                <i className="ri-error-warning-line fs-17"></i>
              </div>
            </div>
            <h3 className="fw-bold text-danger mb-0 mt-2" style={{ fontSize: "28px" }}>
              {logSummary.errors500}
            </h3>
          </div>
        </div>

        {/* 4XX CLIENT ERRORS */}
        <div className="col-12 col-sm-6 col-xl-3">
          <div
            className="card border-0 rounded-4 p-3 bg-white shadow-sm h-100"
            style={{ border: "1px solid #E2E8F0" }}
          >
            <div className="d-flex justify-content-between align-items-center mb-1">
              <span className="fw-bold" style={{ fontSize: "11px", letterSpacing: "0.5px", color: "#D97706" }}>
                4XX CLIENT ERRORS
              </span>
              <div
                className="d-flex align-items-center justify-content-center rounded-3"
                style={{ width: 34, height: 34, backgroundColor: "#FEF3C7", color: "#D97706" }}
              >
                <i className="ri-information-line fs-17"></i>
              </div>
            </div>
            <h3 className="fw-bold mb-0 mt-2" style={{ fontSize: "28px", color: "#D97706" }}>
              {logSummary.errors4xx}
            </h3>
          </div>
        </div>

        {/* ERRORS TODAY */}
        <div className="col-12 col-sm-6 col-xl-3">
          <div
            className="card border-0 rounded-4 p-3 bg-white shadow-sm h-100"
            style={{ border: "1px solid #E2E8F0" }}
          >
            <div className="d-flex justify-content-between align-items-center mb-1">
              <span className="text-primary fw-bold" style={{ fontSize: "11px", letterSpacing: "0.5px" }}>
                ERRORS TODAY
              </span>
              <div
                className="d-flex align-items-center justify-content-center rounded-3"
                style={{ width: 34, height: 34, backgroundColor: "#EFF6FF", color: "#3B82F6" }}
              >
                <i className="ri-calendar-line fs-17"></i>
              </div>
            </div>
            <h3 className="fw-bold text-primary mb-0 mt-2" style={{ fontSize: "28px" }}>
              {logSummary.errorsToday}
            </h3>
          </div>
        </div>
      </div>

      {/* ─── Search Bar & Filters (Matching Screenshot 2) ─────────── */}
      <div className="bg-white rounded-4 shadow-sm p-4" style={{ border: "1px solid #E2E8F0" }}>
        <div className="row g-2 align-items-center mb-4">
          {/* Search input with icon */}
          <div className="col-12 col-md-6 col-lg-7">
            <div className="position-relative">
              <i
                className="ri-search-line text-muted position-absolute"
                style={{ top: "50%", left: "14px", transform: "translateY(-50%)", fontSize: "15px" }}
              />
              <input
                type="text"
                className="form-control rounded-pill ps-5"
                placeholder="Search by endpoint, error message, tenant or user..."
                value={searchQuery}
                onChange={handleSearchChange}
                style={{ fontSize: "13px", padding: "10px 18px 10px 40px", borderColor: "#E2E8F0" }}
              />
            </div>
          </div>

          {/* All Methods dropdown */}
          <div className="col-6 col-md-3 col-lg-2-5">
            <select
              className="form-select rounded-pill"
              value={methodFilter}
              onChange={handleMethodChange}
              style={{ fontSize: "13px", padding: "9px 16px", borderColor: "#E2E8F0" }}
            >
              <option value="ALL">All Methods</option>
              <option value="GET">GET</option>
              <option value="POST">POST</option>
              <option value="PUT">PUT</option>
              <option value="PATCH">PATCH</option>
              <option value="DELETE">DELETE</option>
            </select>
          </div>

          {/* All Status Codes dropdown */}
          <div className="col-6 col-md-3 col-lg-2-5">
            <select
              className="form-select rounded-pill"
              value={statusFilter}
              onChange={handleStatusChange}
              style={{ fontSize: "13px", padding: "9px 16px", borderColor: "#E2E8F0" }}
            >
              <option value="ALL">All Status Codes</option>
              <option value="500">500 Server Errors</option>
              <option value="4xx">4xx Client Errors</option>
              <option value="400">400 Bad Request</option>
              <option value="401">401 Unauthorized</option>
              <option value="403">403 Forbidden</option>
              <option value="404">404 Not Found</option>
              <option value="422">422 Unprocessable</option>
            </select>
          </div>
        </div>

        {/* ─── Table (Columns: TIME, METHOD, STATUS, ENDPOINT, ERROR MESSAGE, TENANT / USER, ACTIONS) */}
        <div className="table-responsive">
          <table className="table align-middle table-hover mb-0">
            <thead>
              <tr className="text-secondary small fw-bold" style={{ fontSize: "11px", letterSpacing: "0.5px" }}>
                <th style={{ minWidth: "140px" }}>TIME</th>
                <th style={{ minWidth: "80px" }}>METHOD</th>
                <th style={{ minWidth: "80px" }}>STATUS</th>
                <th style={{ minWidth: "220px" }}>ENDPOINT</th>
                <th style={{ minWidth: "260px" }}>ERROR MESSAGE</th>
                <th style={{ minWidth: "140px" }}>TENANT / USER</th>
                <th className="text-end" style={{ minWidth: "90px" }}>ACTIONS</th>
              </tr>
            </thead>
            <tbody>
              {logs.length === 0 ? (
                /* Empty state matching Screenshot 2 */
                <tr>
                  <td colSpan={7} className="text-center py-5">
                    <div className="d-flex flex-column align-items-center justify-content-center py-5">
                      <div
                        className="d-flex align-items-center justify-content-center rounded-circle mb-3"
                        style={{ width: 56, height: 56, backgroundColor: "#DCFCE7", color: "#16A34A" }}
                      >
                        <i className="ri-check-line fs-30 fw-bold"></i>
                      </div>
                      <h6 className="fw-bold text-dark mb-1" style={{ fontSize: "16px" }}>
                        No API Error Logs Found
                      </h6>
                      <p className="text-secondary small mb-0" style={{ fontSize: "13px" }}>
                        All API requests are running smoothly with no captured errors!
                      </p>
                    </div>
                  </td>
                </tr>
              ) : (
                logs.map((item: any) => (
                  <tr key={item._id} style={{ fontSize: "13px" }}>
                    {/* Time */}
                    <td className="text-secondary">
                      <div className="fw-semibold text-dark">
                        {new Date(item.createdAt).toLocaleTimeString([], {
                          hour: "2-digit",
                          minute: "2-digit",
                          second: "2-digit",
                        })}
                      </div>
                      <small className="text-muted" style={{ fontSize: "11px" }}>
                        {new Date(item.createdAt).toLocaleDateString()}
                      </small>
                    </td>

                    {/* Method */}
                    <td>
                      <span
                        className={`badge rounded-pill fw-bold px-2 py-1 ${getMethodBadgeClass(item.method)}`}
                        style={{ fontSize: "11px" }}
                      >
                        {item.method}
                      </span>
                    </td>

                    {/* Status */}
                    <td>
                      <span
                        className="badge rounded-pill fw-bold px-2 py-1"
                        style={{ fontSize: "11px", ...getStatusBadgeStyle(item.status) }}
                      >
                        {item.status}
                      </span>
                    </td>

                    {/* Endpoint */}
                    <td className="font-monospace text-truncate" style={{ maxWidth: "240px" }} title={item.endpoint}>
                      {item.endpoint}
                    </td>

                    {/* Error message */}
                    <td className="text-danger fw-medium" style={{ maxWidth: "300px" }}>
                      <span className="text-truncate d-block" title={item.message}>
                        {item.message}
                      </span>
                    </td>

                    {/* Tenant / User */}
                    <td className="text-secondary small">
                      <div>{item.tenant || "quietchat"}</div>
                      <small className="text-muted d-block text-truncate" style={{ maxWidth: "120px" }}>
                        {item.userId || item.ip || "Anonymous"}
                      </small>
                    </td>

                    {/* Actions */}
                    <td className="text-end">
                      <button
                        type="button"
                        className="btn btn-sm btn-light border rounded-pill d-inline-flex align-items-center gap-1"
                        style={{ fontSize: "11px", padding: "4px 12px" }}
                        onClick={() => setSelectedError(item)}
                      >
                        <i className="ri-eye-line"></i> View
                      </button>
                    </td>
                  </tr>
                ))
              )}
            </tbody>
          </table>
        </div>

        {/* Pagination */}
        {pagination.totalPages > 1 && (
          <div className="d-flex justify-content-between align-items-center pt-3 border-top mt-3">
            <span className="text-muted small">
              Showing page {pagination.page} of {pagination.totalPages} ({pagination.total} total logs)
            </span>
            <div className="d-flex gap-1">
              <button
                type="button"
                className="btn btn-sm btn-light border"
                disabled={pagination.page <= 1}
                onClick={() => loadLogs(pagination.page - 1)}
              >
                Prev
              </button>
              <button
                type="button"
                className="btn btn-sm btn-light border"
                disabled={pagination.page >= pagination.totalPages}
                onClick={() => loadLogs(pagination.page + 1)}
              >
                Next
              </button>
            </div>
          </div>
        )}
      </div>

      {/* ─── Detail Modal ─────────────────────────────────────────── */}
      {selectedError && (
        <div
          className="modal fade show d-block"
          style={{ backgroundColor: "rgba(15, 23, 42, 0.65)", backdropFilter: "blur(4px)" }}
          onClick={() => setSelectedError(null)}
        >
          <div
            className="modal-dialog modal-lg modal-dialog-centered"
            onClick={(e) => e.stopPropagation()}
          >
            <div className="modal-content rounded-4 border-0 shadow-lg">
              <div className="modal-header border-bottom px-4 py-3">
                <div className="d-flex align-items-center gap-2">
                  <span
                    className={`badge rounded-pill fw-bold ${getMethodBadgeClass(selectedError.method)}`}
                    style={{ fontSize: "11px" }}
                  >
                    {selectedError.method}
                  </span>
                  <span
                    className="badge rounded-pill fw-bold"
                    style={{ fontSize: "11px", ...getStatusBadgeStyle(selectedError.status) }}
                  >
                    HTTP {selectedError.status}
                  </span>
                  <h6 className="modal-title fw-bold text-dark mb-0 ms-2" style={{ fontSize: "16px" }}>
                    API Failure Trace Details
                  </h6>
                </div>
                <button
                  type="button"
                  className="btn-close"
                  onClick={() => setSelectedError(null)}
                ></button>
              </div>

              <div className="modal-body p-4" style={{ maxHeight: "70vh", overflowY: "auto" }}>
                <div className="mb-3">
                  <label className="text-muted small fw-bold">REQUEST ENDPOINT</label>
                  <div className="p-2 rounded bg-light font-monospace text-dark small">
                    {selectedError.endpoint}
                  </div>
                </div>

                <div className="mb-3">
                  <label className="text-muted small fw-bold">ERROR MESSAGE</label>
                  <div className="p-3 rounded bg-danger-subtle text-danger fw-semibold small">
                    {selectedError.message}
                  </div>
                </div>

                <div className="row g-2 mb-3">
                  <div className="col-6 col-sm-3">
                    <label className="text-muted small fw-bold">LATENCY</label>
                    <div className="fw-semibold text-dark">{selectedError.responseTime || 0} ms</div>
                  </div>
                  <div className="col-6 col-sm-3">
                    <label className="text-muted small fw-bold">CLIENT IP</label>
                    <div className="fw-semibold text-dark">{selectedError.ip || "127.0.0.1"}</div>
                  </div>
                  <div className="col-6 col-sm-3">
                    <label className="text-muted small fw-bold">USER / TENANT</label>
                    <div className="fw-semibold text-dark text-truncate">{selectedError.userId || selectedError.tenant || "Anonymous"}</div>
                  </div>
                  <div className="col-6 col-sm-3">
                    <label className="text-muted small fw-bold">TIMESTAMP</label>
                    <div className="fw-semibold text-dark">
                      {new Date(selectedError.createdAt).toLocaleTimeString()}
                    </div>
                  </div>
                </div>

                {selectedError.requestQuery && Object.keys(selectedError.requestQuery).length > 0 && (
                  <div className="mb-3">
                    <label className="text-muted small fw-bold">URL QUERY PARAMETERS</label>
                    <pre className="p-2 rounded bg-light small mb-0 font-monospace">
                      {JSON.stringify(selectedError.requestQuery, null, 2)}
                    </pre>
                  </div>
                )}

                {selectedError.requestBody && Object.keys(selectedError.requestBody).length > 0 && (
                  <div className="mb-3">
                    <label className="text-muted small fw-bold">REQUEST BODY (SANITIZED)</label>
                    <pre className="p-2 rounded bg-light small mb-0 font-monospace">
                      {JSON.stringify(selectedError.requestBody, null, 2)}
                    </pre>
                  </div>
                )}

                {selectedError.stackTrace && (
                  <div className="mb-3">
                    <label className="text-muted small fw-bold">SERVER EXCEPTION STACK TRACE</label>
                    <pre className="p-2 rounded bg-dark text-white small mb-0 font-monospace" style={{ fontSize: "11px" }}>
                      {selectedError.stackTrace}
                    </pre>
                  </div>
                )}
              </div>

              <div className="modal-footer border-top px-4 py-2">
                <button
                  type="button"
                  className="btn btn-secondary btn-sm rounded-pill px-4"
                  onClick={() => setSelectedError(null)}
                >
                  Close
                </button>
              </div>
            </div>
          </div>
        </div>
      )}

      <style jsx>{`
        .spin-anim {
          animation: spin 1s linear infinite;
        }
        @keyframes spin {
          from { transform: rotate(0deg); }
          to { transform: rotate(360deg); }
        }
      `}</style>
    </div>
  );
};

ApiErrorLogsPage.getLayout = function getLayout(page: React.ReactNode) {
  return <RootLayout>{page}</RootLayout>;
};

export default ApiErrorLogsPage;
